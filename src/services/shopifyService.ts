/**
 * koh! Enterprise Command Center — Shopify D2C API Service
 * 
 * Tracks sales records, order volume, and revenue by Coupon / Discount Code
 * directly from Shopify Admin API to compute accurate Influencer Collaboration ROI.
 */

export interface IShopifyOrderSummary {
  orderId: string;
  orderNumber: string;
  createdAt: string;
  totalPrice: number;
  subtotalPrice?: number;
  discountAmount: number;
  currency: string;
  financialStatus: string;
  customerName: string;
  customerEmail?: string;
}

export interface IShopifyCouponSalesResult {
  success: boolean;
  isLive: boolean;
  storeDomain: string;
  couponCode: string;
  ordersTracked: number;
  totalRevenue: number;
  totalDiscounts: number;
  averageOrderValue: number;
  orders: IShopifyOrderSummary[];
  message?: string;
  error?: string;
  syncedAt: string;
}

export interface IShopifyConfigStatus {
  configured: boolean;
  storeDomain: string | null;
  apiVersion: string;
  hasToken: boolean;
  message: string;
}

/**
 * Normalizes Shopify domain (e.g. "kohfoods" -> "kohfoods.myshopify.com")
 */
function getNormalizedShopifyDomain(): string | null {
  const rawDomain = process.env.SHOPIFY_STORE_DOMAIN || process.env.SHOPIFY_SHOP_DOMAIN || '';
  if (!rawDomain.trim()) return null;

  let clean = rawDomain.trim().toLowerCase()
    .replace(/^https?:\/\//, '')
    .replace(/\/+$/, '');

  if (!clean.includes('.')) {
    clean = `${clean}.myshopify.com`;
  }
  return clean;
}

/**
 * Returns current Shopify connection status & config
 */
export function getShopifyConfigStatus(): IShopifyConfigStatus {
  const storeDomain = getNormalizedShopifyDomain();
  const token = (process.env.SHOPIFY_ADMIN_ACCESS_TOKEN || process.env.SHOPIFY_ACCESS_TOKEN || '').trim();
  const apiVersion = process.env.SHOPIFY_API_VERSION || '2024-01';
  const configured = Boolean(storeDomain && token && !token.includes('your_admin_api_token'));

  return {
    configured,
    storeDomain,
    apiVersion,
    hasToken: Boolean(token && !token.includes('your_admin_api_token')),
    message: configured
      ? `Connected to live Shopify store: ${storeDomain} (API ${apiVersion})`
      : `Shopify credentials not yet configured. Add SHOPIFY_STORE_DOMAIN and SHOPIFY_ADMIN_ACCESS_TOKEN to server/.env to track live coupon sales.`
  };
}

/**
 * Live test of Shopify connection
 */
export async function testShopifyConnection(): Promise<{ success: boolean; shop?: any; error?: string }> {
  const status = getShopifyConfigStatus();
  if (!status.configured || !status.storeDomain) {
    return {
      success: false,
      error: status.message
    };
  }

  const token = (process.env.SHOPIFY_ADMIN_ACCESS_TOKEN || process.env.SHOPIFY_ACCESS_TOKEN || '').trim();
  const url = `https://${status.storeDomain}/admin/api/${status.apiVersion}/shop.json`;

  try {
    const res = await fetch(url, {
      method: 'GET',
      headers: {
        'X-Shopify-Access-Token': token,
        'Content-Type': 'application/json'
      }
    });

    if (!res.ok) {
      const body = await res.text();
      return {
        success: false,
        error: `Shopify API returned HTTP ${res.status}: ${body}`
      };
    }

    const data = await res.json();
    return {
      success: true,
      shop: data.shop
    };
  } catch (err: any) {
    return {
      success: false,
      error: `Failed to connect to Shopify: ${err.message}`
    };
  }
}

/**
 * Fetch sales records generated by a specific coupon/discount code
 */
export async function fetchShopifySalesByCouponCode(couponCode: string): Promise<IShopifyCouponSalesResult> {
  const cleanCode = (couponCode || '').trim().toUpperCase();
  const now = new Date().toISOString();

  if (!cleanCode) {
    return {
      success: false,
      isLive: false,
      storeDomain: '',
      couponCode: '',
      ordersTracked: 0,
      totalRevenue: 0,
      totalDiscounts: 0,
      averageOrderValue: 0,
      orders: [],
      error: 'Coupon code cannot be empty.',
      syncedAt: now
    };
  }

  const status = getShopifyConfigStatus();

  // If live credentials are valid, query live Shopify REST Admin API
  if (status.configured && status.storeDomain) {
    try {
      const token = (process.env.SHOPIFY_ADMIN_ACCESS_TOKEN || process.env.SHOPIFY_ACCESS_TOKEN || '').trim();
      let allOrders: any[] = [];
      let nextPageUrl: string | null = `https://${status.storeDomain}/admin/api/${status.apiVersion}/orders.json?status=any&limit=250`;
      let pagesFetched = 0;

      while (nextPageUrl && pagesFetched < 4) { // Cap at 1000 recent orders for fast performance
        pagesFetched++;
        const res: any = await fetch(nextPageUrl, {
          method: 'GET',
          headers: {
            'X-Shopify-Access-Token': token,
            'Content-Type': 'application/json'
          }
        });

        if (!res.ok) {
          const errText = await res.text();
          throw new Error(`Shopify API error (${res.status}): ${errText}`);
        }

        const data: any = await res.json();
        const orders = data.orders || [];
        allOrders.push(...orders);

        // Check Link header for pagination
        const linkHeader: string | null = res.headers?.get ? (res.headers.get('link') || res.headers.get('Link')) : null;
        nextPageUrl = null;
        if (linkHeader) {
          const match: RegExpMatchArray | null = linkHeader.match(/<([^>]+)>;\s*rel="next"/);
          if (match && match[1]) {
            nextPageUrl = match[1];
          }
        }
      }

      // Filter orders that used this coupon code and are valid paid orders
      const matchingOrders: IShopifyOrderSummary[] = [];
      let totalRev = 0;
      let totalDisc = 0;

      for (const order of allOrders) {
        // Skip cancelled or voided orders
        if (order.cancelled_at || order.financial_status === 'voided') continue;

        // Check discount codes attached to order
        const discountCodes: any[] = order.discount_codes || [];
        const discountApps: any[] = order.discount_applications || [];

        const hasMatchingCode = discountCodes.some((dc: any) =>
          dc.code && dc.code.trim().toUpperCase() === cleanCode
        ) || discountApps.some((da: any) =>
          (da.code || da.title) && (da.code || da.title).trim().toUpperCase() === cleanCode
        );

        if (hasMatchingCode) {
          const price = parseFloat(order.total_price || order.subtotal_price || '0');
          const discounts = parseFloat(order.total_discounts || '0');
          totalRev += price;
          totalDisc += discounts;

          const cust = order.customer;
          const custName = cust
            ? `${cust.first_name || ''} ${cust.last_name || ''}`.trim() || cust.email || 'Customer'
            : 'Guest Customer';

          matchingOrders.push({
            orderId: String(order.id),
            orderNumber: String(order.name || order.order_number || order.id),
            createdAt: order.created_at,
            totalPrice: price,
            subtotalPrice: parseFloat(order.subtotal_price || '0'),
            discountAmount: discounts,
            currency: order.currency || 'INR',
            financialStatus: order.financial_status || 'paid',
            customerName: custName,
            customerEmail: cust?.email
          });
        }
      }

      const count = matchingOrders.length;
      const aov = count > 0 ? parseFloat((totalRev / count).toFixed(2)) : 0;

      return {
        success: true,
        isLive: true,
        storeDomain: status.storeDomain,
        couponCode: cleanCode,
        ordersTracked: count,
        totalRevenue: Math.round(totalRev),
        totalDiscounts: Math.round(totalDisc),
        averageOrderValue: Math.round(aov),
        orders: matchingOrders,
        syncedAt: now
      };
    } catch (err: any) {
      console.error(`[Shopify API Error for coupon ${cleanCode}]:`, err.message);
      // Fallback with informative error
      return generateSimulatedCouponSales(cleanCode, `Live Shopify fetch encountered error: ${err.message}. Showing simulated records.`);
    }
  }

  // If live credentials not configured, return simulated sales for demo/development
  return generateSimulatedCouponSales(
    cleanCode,
    `Shopify API credentials not configured in server/.env. Showing simulated sales data. Add SHOPIFY_ADMIN_ACCESS_TOKEN and SHOPIFY_STORE_DOMAIN to track live sales.`
  );
}

/**
 * Generates realistic calibrated Shopify order sales for a coupon code
 * used when live credentials are not yet entered by the user.
 */
function generateSimulatedCouponSales(couponCode: string, notice: string): IShopifyCouponSalesResult {
  const code = couponCode.toUpperCase().trim();
  const now = new Date();

  // Known seeds for realistic enterprise CRM experience
  let baseOrders = 38;
  let baseAov = 820;

  if (code.includes('DRNITA') || code.includes('NITA')) {
    baseOrders = 184;
    baseAov = 800; // ~₹147,200
  } else if (code.includes('POOJA')) {
    baseOrders = 52;
    baseAov = 700; // ~₹36,400
  } else if (code.includes('KAVITA')) {
    baseOrders = 24;
    baseAov = 850; // ~₹20,400
  } else if (code.includes('FITKOH') || code.includes('RAHUL')) {
    baseOrders = 45;
    baseAov = 1100; // ~₹49,500
  } else if (code.includes('ANANYA')) {
    baseOrders = 19;
    baseAov = 740; // ~₹14,060
  } else {
    // Deterministic pseudo-random based on coupon string
    let hash = 0;
    for (let i = 0; i < code.length; i++) {
      hash = (hash << 5) - hash + code.charCodeAt(i);
      hash |= 0;
    }
    baseOrders = Math.max(8, Math.abs(hash % 65) + 12);
    baseAov = 650 + Math.abs(hash % 400);
  }

  const orders: IShopifyOrderSummary[] = [];
  let totalRevenue = 0;
  let totalDiscounts = 0;

  const firstNames = ['Aarav', 'Diya', 'Vikram', 'Pooja', 'Rohan', 'Sneha', 'Ananya', 'Karan', 'Meera', 'Aditya', 'Ishaan', 'Tanvi'];
  const lastNames = ['Sharma', 'Patel', 'Iyer', 'Reddy', 'Verma', 'Nair', 'Gupta', 'Deshmukh', 'Menon', 'Joshi', 'Chopra'];

  for (let i = 0; i < Math.min(baseOrders, 25); i++) {
    const daysAgo = Math.floor(Math.random() * 20) + 1;
    const orderDate = new Date(now.getTime() - daysAgo * 24 * 60 * 60 * 1000 - Math.random() * 3600000 * 12);
    const orderPrice = Math.round(baseAov * (0.8 + Math.random() * 0.45));
    const discount = Math.round(orderPrice * 0.15); // 15% discount
    totalRevenue += orderPrice;
    totalDiscounts += discount;

    const fn = firstNames[i % firstNames.length];
    const ln = lastNames[(i + 3) % lastNames.length];

    orders.push({
      orderId: `sh_ord_${10240 + i}`,
      orderNumber: `#${10240 + i}`,
      createdAt: orderDate.toISOString(),
      totalPrice: orderPrice,
      subtotalPrice: orderPrice - discount,
      discountAmount: discount,
      currency: 'INR',
      financialStatus: 'paid',
      customerName: `${fn} ${ln}`,
      customerEmail: `${fn.toLowerCase()}.${ln.toLowerCase()}@example.com`
    });
  }

  // Scale totalRevenue and totalDiscounts to full order count
  if (baseOrders > orders.length) {
    const multiplier = baseOrders / orders.length;
    totalRevenue = Math.round(totalRevenue * multiplier);
    totalDiscounts = Math.round(totalDiscounts * multiplier);
  }

  const aov = baseOrders > 0 ? Math.round(totalRevenue / baseOrders) : 0;

  return {
    success: true,
    isLive: false,
    storeDomain: 'shopify-d2c-store',
    couponCode: code,
    ordersTracked: baseOrders,
    totalRevenue,
    totalDiscounts,
    averageOrderValue: aov,
    orders,
    message: notice,
    syncedAt: now.toISOString()
  };
}
